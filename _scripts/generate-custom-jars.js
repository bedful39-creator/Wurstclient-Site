// Scans download/jars/ for custom Wurst builds and writes _data/custom_jars.yml.
// Run it after adding or removing files: node _scripts/generate-custom-jars.js
// The deploy workflow runs it automatically before building.
//
// Files are matched by their official names, e.g.
//   download/jars/Wurst-Client-v7.54-MC26.2.jar
//   download/jars/Wurst-Client-v7.54-MC26.2-sources.jar
//   download/jars/Wurst-Client-v6.21-MC1.8.zip
//
// Files that still contain the placeholder marker are ignored, so downloads
// without a real file fall back to download/jars/Wurst-Client-V8.1-MC.jar.
// Use _scripts/create-placeholder-jars.js to create one placeholder per
// download, then replace the ones you have builds for.

const fs = require('fs');
const path = require('path');
const {
    ROOT,
    JARS_DIR,
    DATA_FILE,
    SITE_DIR,
    FALLBACK_FILE,
    FALLBACK_URL,
    listFiles,
    isPlaceholder
} = require('./custom-jars-lib.js');

function scanCustomJars() {
    const files = {};
    for (const relative of listFiles(JARS_DIR)) {
        const name = path.posix.basename(relative);
        if (name.toLowerCase() === FALLBACK_FILE.toLowerCase())
            continue;
        if (isPlaceholder(path.join(JARS_DIR, ...relative.split('/'))))
            continue;
        if (files[name]) {
            console.warn(`Duplicate file name "${name}": keeping ${files[name]}, ignoring ${SITE_DIR}/${relative}`);
            continue;
        }
        files[name] = `${SITE_DIR}/${relative}`;
    }
    return { fallback: FALLBACK_URL, files };
}

function serialize({ fallback, files }) {
    const lines = [
        '# Generated by _scripts/generate-custom-jars.js - do not edit by hand.',
        `fallback: ${JSON.stringify(fallback)}`
    ];
    const names = Object.keys(files).sort((a, b) => a.localeCompare(b));
    if (names.length === 0) {
        lines.push('files: {}');
    } else {
        lines.push('files:');
        for (const name of names)
            lines.push(`  ${JSON.stringify(name)}: ${JSON.stringify(files[name])}`);
    }
    return lines.join('\n') + '\n';
}

function writeCustomJars() {
    const jars = scanCustomJars();
    fs.writeFileSync(DATA_FILE, serialize(jars));
    return jars;
}

if (require.main === module) {
    const jars = writeCustomJars();

    const count = Object.keys(jars.files).length;
    const fallbackPath = path.join(JARS_DIR, FALLBACK_FILE);
    const fallbackState = !fs.existsSync(fallbackPath) ? 'MISSING'
        : isPlaceholder(fallbackPath) ? 'still a placeholder'
            : 'found';

    console.log(`Mapped ${count} custom file(s); fallback ${FALLBACK_FILE} ${fallbackState}.`);
    console.log(`Wrote ${path.relative(ROOT, DATA_FILE)}`);
}

module.exports = { scanCustomJars, writeCustomJars };
